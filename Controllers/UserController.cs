        /// 通过邮箱链接验证来重置密码 - 重置密码时输入密码
        /// </summary>
        /// <returns></returns>
        [HttpPost("reset-password")]
        public async Task<Result> ResetPassword(ResetBody body)
        {
            ResetPasswordTempEntity? resetTemp = await _primaryDbContext.ResetPasswordTemps.FindAsync(body.Id);
            if (resetTemp is null) return Result.Failed(-1, "The reset link has expired");
            UserEntity user = await _primaryDbContext.Users.Where(u => u.Email == resetTemp.Email).FirstAsync();
            user.Password = EncryptionHelper.Sha1(body.Password!.Trim());
            _primaryDbContext.ResetPasswordTemps.Remove(resetTemp);
            await _primaryDbContext.SaveChangesAsync();
            return Result.Success(null);
        }

        [HttpGet("times")]
        public async Task<Result> GetTimes()
        {
            string? userId = _httpContextAccessor.HttpContext?.User?.Claims.FirstOrDefault(i => i.Type == "id")?.Value;
            if (userId == null) return Result.Failed(-2, "Please login again.");
            var t = await _primaryDbContext.Users.Where(u => u.Id == new Guid(userId)).Select(i => new
            {
                Times = i.Times,
                ExpireTime = i.ExpiredTime
            }).FirstAsync();
            if (t.ExpireTime < DateTime.UtcNow)
            {
                await _primaryDbContext.Users.Where(u => u.Id == new Guid(userId)).ExecuteUpdateAsync(u => u.SetProperty(i => i.ExpiredTime, (DateTime?)null).SetProperty(i => i.Times, 0));
                return Result.Success(0);
            }
            return Result.Success(t.Times);
        }

        [HttpGet("is-preview")]
        public async Task<Result> IsPreview()
        {
            string? userId = _httpContextAccessor.HttpContext?.User?.Claims.FirstOrDefault(i => i.Type == "id")?.Value;
            if (userId == null) return Result.Failed(-2, "Please login again.");
            return Result.Success(await _primaryDbContext.Users.Where(u => u.Id == new Guid(userId)).Select(u => u.IsPreview).FirstAsync());
        }

