        /// <summary>
        /// 用户注册
        /// </summary>
        /// <param name="body"></param>
        /// <returns></returns>
        [HttpPost("register")]
        public async Task<Result> Register(RegisterBody body)
        {
            // 1.参数检查
            var email = body.Email?.Trim();
            if (string.IsNullOrEmpty(email)) return Result.Failed(-1, "The parameter is required: email"); // TODO 当前仅支持邮箱登录

            // 1.2 查询临时信息，如果已经注册但未验证链接，则重新发送链接并重置超时时间
            RegistinfoTempEntity? isRepeat = await _primaryDbContext.RegistinfoTemps.Where(i => i.Email == body.Email).FirstOrDefaultAsync();
            if (isRepeat is not null)
            {
                isRepeat.CreateTime = DateTime.UtcNow;
                isRepeat.Password = EncryptionHelper.Sha1(body.Password!.Trim());
                await _primaryDbContext.SaveChangesAsync();
                var flag_ = await this.SendEmail(email!, $"{_configuration["ApplicationUrl"]}/api/v1/user/verifyRegistUrl/{isRepeat.Id}", body.Language);
                if (!flag_) return Result.Failed(-1, "Send email failed");
                return Result.Success(null);
            }

            UserEntity? isRegist = await _primaryDbContext.Users.Where(i => i.Email == body.Email).FirstOrDefaultAsync();
            if (isRegist is not null)
                return Result.Failed(-1, "The current email address has already been registered");

            // 2.保存临时信息到数据库
            RegistinfoTempEntity usertemp = new RegistinfoTempEntity()
            {
                Id = Guid.NewGuid(),
                Email = email,
                Password = EncryptionHelper.Sha1(body.Password!.Trim()),
                CreateTime = DateTime.UtcNow,
            };
            var tempuser = await _primaryDbContext.RegistinfoTemps.AddAsync(usertemp);
            await _primaryDbContext.SaveChangesAsync();

            // 4.发送邮箱
            var flag = await this.SendEmail(email!, $"{_configuration["ApplicationUrl"]}/api/v1/user/verifyRegistUrl/{usertemp.Id}", body.Language);
            if (!flag) return Result.Failed(-1, "Send email failed");
            return Result.Success(null);
        }

