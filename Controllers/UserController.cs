        [HttpPost("modify-password")]
        [Authorize]
        public async Task<Result> ChangePassword(ChangePasswordBody body)
        {
            string? userId = _httpContextAccessor.HttpContext?.User?.Claims.FirstOrDefault(i => i.Type == "id")?.Value;
            if (userId == null) return Result.Failed(-2, "Please login again.");

            // 2. 修改数据
            UserEntity? user = await _primaryDbContext.Users.Where(u => u.Id == new Guid(userId) && u.Password == EncryptionHelper.Sha1(body.OldPassword!.Trim())).FirstOrDefaultAsync();
            if (user is null) return Result.Failed(-1, "Old Password is wrong");
            else
            {
                user.Password = EncryptionHelper.Sha1(body.NewPassword!.Trim());
                await _primaryDbContext.SaveChangesAsync();
                return Result.Success("change password successful");
            }
        }

