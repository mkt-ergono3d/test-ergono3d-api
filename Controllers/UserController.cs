        /// <summary>
        /// 用户登录
        /// </summary>
        [HttpPost("login")]
        public async Task<Result> Login(LoginBody body)
        {
            var email = body.Email?.Trim();
            if (string.IsNullOrEmpty(email)) return Result.Failed(-1, "The parameter is required: email"); // TODO 当前仅支持邮箱登录

            var password = EncryptionHelper.Sha1(body.Password!.Trim());
            var user = await _primaryDbContext.Users.Where(u => u.Email == email && u.Password == password).FirstOrDefaultAsync();
            if (user == null) return Result.Failed(-2, "Login failed!");

            bool isFirst = user.CreateTime == DateTime.MinValue;
            if (isFirst)
            {
                user.CreateTime = DateTime.UtcNow;
                await _primaryDbContext.SaveChangesAsync();
            }
            var token = _jwtHelper.GenerateToken(user);

            return Result.Success(new { token, user_id = user.Id, user_name = user.Name, email = user.Email, is_first = isFirst, vip_expire = user.ExpiredTime });
        }

        [HttpPost("login/google")]
        public async Task<Result> GoogleLogin([FromBody] string credential)
        {
            try
            {
                Payload payload = await ValidateAsync(credential, new ValidationSettings());
                // 判断token的应用id、google域名、有效期
                if (payload.Audience.ToString() != _configuration["GoogleLogin-ClientId"] || payload.Issuer != "https://accounts.google.com"
                    || new DateTimeOffset(DateTime.UtcNow.AddMinutes(-15)).ToUnixTimeSeconds() > payload.ExpirationTimeSeconds) throw new Exception();
                UserEntity user = await LoginOrRegist(payload.Email, payload.Name.Substring(0, Math.Min(payload.Name.Length, 20)), false);
                bool isFirst = user.CreateTime == DateTime.MinValue;
                if (isFirst)
                {
                    user.CreateTime = DateTime.UtcNow;
                    await _primaryDbContext.SaveChangesAsync();
                }
                var token = _jwtHelper.GenerateToken(user);
                return Result.Success(new { token, user_id = user.Id, user_name = user.Name, email = user.Email, is_first = isFirst, vip_expire = user.ExpiredTime });
            }
            catch
            {
                return Result.Failed(-1, "Google login verification failed.");
            }
        }

